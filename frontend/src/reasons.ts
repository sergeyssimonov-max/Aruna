/**
 * Названия причин, по которым документ не является корректным XML.
 *
 * Ключи приходят из манифеста пакета и объявлены в ядре
 * (`cli/src/xml_wellformed.rs`); здесь только то, как их назвать человеку.
 *
 * **Слова взяты не отсюда, а из спецификации, §4.13.** Там эти же девять
 * причин перечислены таблицей с числами, и второе их название – придуманное
 * при переводе окна – разошлось бы с первым молча. Один текст в двух местах
 * сличается глазами; два разных текста об одном не сличается ничем.
 *
 * **По-русски, потому что окно русское.** До 06.09.2026 подписи были
 * английские, и это было наследство: причины появились вместе с описью, а
 * опись – документ англоязычный. В описи их не показывают нигде; их читают
 * только в окне, где все остальное – заголовки, стадии, кнопки – по-русски.
 *
 * **Слова выбраны так, чтобы не соврать в две стороны сразу.** Документ не
 * испорчен программой – он таким пришел из корпуса; и он не отвергнут – он
 * лежит в пакете вместе со всеми. Поэтому нигде нет ни «ошибки», ни
 * «отклонен», ни «поврежден»: строки описывают разметку, а не судьбу файла.
 * Слово «некорректный» при этом разрешено – так эти документы называет сама
 * спецификация, и оно говорит о разметке, а не о вине.
 */
const NAMES: Record<string, string> = {
  'unterminated-start-tag': 'начатый тег без закрывающей скобки',
  'attribute-not-separated': 'атрибут не отделен «=»',
  'attribute-value-unclosed': 'значение атрибута не закрыто до конца файла',
  'attribute-given-twice': 'атрибут задан дважды',
  'element-never-closed': 'элемент не закрыт нигде',
  'crossing-elements': 'пересечение элементов',
  'duplicate-end-tag': 'повторный закрывающий тег',
  'no-such-element': 'закрывающего элемента в документе нет',
  'mismatched-end-tag-name': 'несогласованное имя закрывающего тега',
  unclassified: 'не классифицирован',
}

/**
 * Как назвать причину человеку.
 *
 * Незнакомый ключ возвращается как есть, а не подменяется на «неизвестно».
 * Манифест старше окна – обычное дело: ядро может научиться новой причине
 * раньше, чем окно узнает ее имя, и показать ключ честнее, чем скрыть строку
 * или назвать ее пустым словом. Читателю ключ понятен: он же стоит в файле.
 */
export function reasonName(key: string): string {
  return NAMES[key] ?? key
}

/**
 * Известные ключи – для теста, который держит их вместе с ядром.
 */
export const KNOWN_REASONS: readonly string[] = Object.keys(NAMES)
